-- 요청 단위의 영속 업무 메모리 POC_V2_RUNS를 생성한다.
-- 사용자 turn, 원문, 표준화 문맥, SQL/승인/실행 버전, 결과, 잠금 토큰과 단계 예산을 보관한다. 기존 SH/사전에는 쓰지 않는다.

-- SH 및 표준화/업무 메타데이터는 읽기 전용으로 재사용한다.
CREATE TABLE POC_V2_RUNS (
 request_id VARCHAR2(32) CONSTRAINT POC_V2_RUNS_PK PRIMARY KEY,
 conversation_id VARCHAR2(128) NOT NULL,
 client_turn_id VARCHAR2(128) NOT NULL,
 execution_conversation_id VARCHAR2(128),
 original_question VARCHAR2(4000 CHAR) NOT NULL,
 effective_question VARCHAR2(4000 CHAR) NOT NULL,
 revision NUMBER DEFAULT 1 NOT NULL,
 sql_version NUMBER DEFAULT 0 NOT NULL,
 approved_revision NUMBER,
 approved_sql_version NUMBER,
 executed_revision NUMBER,
 executed_sql_version NUMBER,
 report_revision NUMBER,
 approved_sql CLOB,
 executed_sql CLOB,
 state VARCHAR2(40) DEFAULT 'NEW' NOT NULL,
 requested_action VARCHAR2(30),
 execute_allowed CHAR(1) DEFAULT 'N' NOT NULL,
 generation_attempts NUMBER DEFAULT 0 NOT NULL,
 execution_attempts NUMBER DEFAULT 0 NOT NULL,
 flow_steps NUMBER DEFAULT 0 NOT NULL,
 max_steps NUMBER DEFAULT 20 NOT NULL,
 deadline_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP + INTERVAL '15' MINUTE NOT NULL,
 context_json CLOB DEFAULT '{}',
 requirements_json CLOB,
 sql_text CLOB,
 columns_json CLOB,
 pre_review_json CLOB,
 result_json CLOB,
 post_review_json CLOB,
 report CLOB,
 raw_agent_output CLOB,
 runner_active CHAR(1) DEFAULT 'N' NOT NULL,
 runner_token VARCHAR2(32),
 last_error VARCHAR2(2000),
 events_json CLOB DEFAULT '[]' NOT NULL,
 created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
 CONSTRAINT POC_V2_TURN_UQ UNIQUE(conversation_id,client_turn_id),
 CONSTRAINT POC_V2_CONTEXT_CK CHECK(context_json IS JSON),
 CONSTRAINT POC_V2_REQ_CK CHECK(requirements_json IS JSON),
 CONSTRAINT POC_V2_RESULT_CK CHECK(result_json IS JSON),
 CONSTRAINT POC_V2_EVENTS_CK CHECK(events_json IS JSON)
);
